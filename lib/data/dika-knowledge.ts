export function getDikaEntry(slug: string) {
  return dikaKnowledge.find((entry) => entry.slug === slug)
}

export function getRelatedDika(entry: DikaEntry, count = 3): DikaEntry[] {
  const sameCategory = dikaKnowledge.filter((item) => item.slug !== entry.slug && item.category === entry.category)
  const others = dikaKnowledge.filter((item) => item.slug !== entry.slug && item.category !== entry.category)
  return [...sameCategory, ...others].slice(0, count)
}